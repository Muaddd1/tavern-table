import classes from "@/data/srd/classes.json";
import subclasses from "@/data/srd/subclasses.json";
import species from "@/data/srd/species.json";
import lineages from "@/data/srd/lineages.json";
import backgrounds from "@/data/srd/backgrounds.json";
import feats from "@/data/srd/feats.json";
import items from "@/data/srd/items.json";
import { FEATURE_EFFECTS } from "@/data/srd/mechanics";
import type { BackgroundDef, ClassDef, Compendium, FeatDef, Feature, HomebrewPack, ItemDef, LineageDef, SpeciesDef, SubclassDef } from "./types";

const withEffects = (f: Feature): Feature => ({ ...f, effects: f.effects ?? FEATURE_EFFECTS[f.id] });
const byId = <T extends { id: string }>(list: T[]) => new Map(list.map((x) => [x.id, x]));

// JSON is generated by scripts/import-srd.mjs, whose output these types describe.
export const srd: Compendium = {
  classes: byId((classes as unknown as ClassDef[]).map((c) => ({ ...c, levels: c.levels.map((l) => ({ ...l, features: l.features.map(withEffects) })) }))),
  subclasses: byId((subclasses as unknown as SubclassDef[]).map((s) => ({ ...s, features: s.features.map(withEffects) }))),
  species: byId((species as unknown as SpeciesDef[]).map((s) => ({ ...s, traits: s.traits.map(withEffects) }))),
  lineages: byId((lineages as unknown as LineageDef[]).map((s) => ({ ...s, traits: s.traits.map(withEffects) }))),
  backgrounds: byId(backgrounds as unknown as BackgroundDef[]),
  feats: byId((feats as unknown as FeatDef[]).map((f) => ({ ...f, effects: f.effects ?? FEATURE_EFFECTS[f.id] }))),
  items: byId(items as unknown as ItemDef[]),
};

// Homebrew entries use the same data format and sit on top of the SRD.
export function withHomebrew(base: Compendium, pack?: HomebrewPack): Compendium {
  if (!pack) return base;
  const merge = <T extends { id: string }>(m: Map<string, T>, list?: T[]) => (list?.length ? new Map([...m, ...list.map((x) => [x.id, x] as const)]) : m);
  return {
    classes: merge(base.classes, pack.classes), subclasses: merge(base.subclasses, pack.subclasses), species: merge(base.species, pack.species),
    lineages: merge(base.lineages, pack.lineages), backgrounds: merge(base.backgrounds, pack.backgrounds), feats: merge(base.feats, pack.feats), items: merge(base.items, pack.items),
  };
}
